// Ark reach v1 (owner rule, decision 416: "if animals can't reach eachother - no mating / reproduction occurs"). Lane
// ARK-REACHABLE-MATES, docs/ark/reachable-mates.md.
//
// Which parts of an island an animal can get to on its own, from the atlas's mask (the scene's population-independent
// grid: land, fresh water, shallow sea, deep sea, 2 m cells), and so whether two homes are joined by a path it can
// travel. Precomputed: the cells it can be on are labelled into connected parts once per atlas, island and way of
// moving (a handful of ways), so a question is one cell lookup, never a path search.
//
// How it moves is the atlas's own sheet, read by the same rule positions.ts uses to keep a hunter's foray on ground it
// can be on (onMedium, private there; its truth table is repeated below and pinned by reach.test.ts):
//   - a flier (sheet.flies) goes anywhere on its island: one part, the island;
//   - a water animal (aquatic, not amphibious) stays in water of its kind (fresh, salt, or either when the sheet names
//     none): one connected body of water;
//   - an amphibious one goes on land and in any water;
//   - everything else (walk, climb, hop, crawl, slither, burrow, perch, cling, sessile) is a land animal: land only, and
//     a big one (drawn length 1.2 m or more) wades fresh water and the shallow sea, as the scene lets it. The mask holds
//     no cliff, fence or tree, so climbers and burrowers have no rule of their own: they go where land goes.
// Cells join their four side neighbours (never only at a corner: a river one cell wide on a diagonal still parts the
// land). Off the mask is deep sea.
//
// The TOWN (lane TOWN-REACH, docs/ark/town-reach.md): its mask (`town-reach.json`, generated by the web from the town's own
// layout) carries four flags above the medium that the wild island's mask never sets, so nothing above changes for the wild:
// BAR a building's wall or a barrier line (hedge, wall, fence, zoo fence, net...) on a land cell, SMALL / CLIMB that a small /
// a climbing body gets through it, DECK a bridge's deck over a water cell. A way of moving then has a fifth character: who it
// is on a barrier, "n" (a walker: stopped by every barrier), "s" (small: through what lets small through), "c" (a climber)
// or "b" (both). A way of four characters is a walker. A flier is still "air": anywhere on its island.
//
// Same rules as positions.ts: pure, import-free and ES5-safe at runtime (no Map/Set, no Math.imul, no `??`), so the
// web can take a byte-identical copy to draw who can reach whom. It changes nothing positions.ts answers.

export const REACH_VERSION = 2;

/** The flags of a town mask's cell above its medium (low two bits). The wild island's mask has none of them. */
export const BAR = 4;
export const SMALL = 8;
export const CLIMB = 16;
export const DECK = 32;

/** Drawn length (m) up to which a body is "small" on a barrier: it goes under a rail (0.4 m high) and through a hedge (0.3 m gap) at the scene's default proportions (height 0.5, width 0.35 of its length). */
export const SMALL_LEN = 0.8;

/** The fields of an atlas sheet this reads (positions.ts Sheet). */
export interface ReachSheet {
  len: number;
  water: string;
  flies: boolean;
  aquatic: boolean;
  amphibious: boolean;
}

/** The atlas's island mask (positions.ts AtlasIsland.mask, decoded: one byte a cell, medium in its low two bits). */
export interface ReachMask {
  x0: number;
  z0: number;
  cell: number;
  nx: number;
  nz: number;
  data: number[];
}

/**
 * Can it be on this medium (0 land, 1 fresh water, 2 shallow sea, 3 deep sea)? positions.ts onMedium's rule, verbatim.
 */
export function canBeOn(sheet: ReachSheet, medium: number): boolean {
  if (sheet.flies) return true;
  if (medium <= 0) return !sheet.aquatic || sheet.amphibious;
  if (sheet.aquatic || sheet.amphibious) return sheet.water === "" || (medium === 1 ? sheet.water !== "salt" : sheet.water !== "fresh") || sheet.amphibious;
  return medium === 2 || medium === 1 ? sheet.len >= 1.2 : false;
}

/**
 * Its way of moving as the media it can be on: "air" for a flier (the whole island), else four 0/1 digits for land,
 * fresh water, shallow sea, deep sea ("1000" a land animal, "0100" a freshwater fish, "1111" amphibious).
 */
export function wayOf(sheet: ReachSheet): string {
  if (sheet.flies) return "air";
  let s = "";
  for (let m = 0; m < 4; m++) s += canBeOn(sheet, m) ? "1" : "0";
  return s;
}

/** Who a body is on a barrier, as the fifth character of its way: "n" a walker, "s" small, "c" a climber, "b" small and a climber. */
export function passLetter(small: boolean, climbs: boolean): string {
  return small ? (climbs ? "b" : "s") : climbs ? "c" : "n";
}

function passBits(way: string): number {
  const c = way.charAt(4);
  return c === "s" ? 1 : c === "c" ? 2 : c === "b" ? 3 : 0;
}

/**
 * Its way of moving on a town mask (docs/ark/town-reach.md): `air` for a flier (the scene's own `flies`: it moves by flight,
 * which the sheet's `flies` flag, a flier by its main way of moving only, misses: a crow walks and flies), else the media of
 * `wayOf(sheet)` and who it is on a barrier: small up to SMALL_LEN, a climber when its kind climbs walls (`climbs`).
 */
export function townWayOf(sheet: ReachSheet, flies: boolean, climbs: boolean): string {
  if (flies) return "air";
  return wayOf(sheet) + passLetter(sheet.len <= SMALL_LEN, climbs);
}

interface Labels {
  mask: ReachMask;
  /** Per cell: its part (0, 1, ...), or -1 where it cannot be. */
  part: number[];
  parts: number;
}

/** Labels by mask, by way: a mask object is the atlas's own, kept for the atlas's life (no Map: ES5). */
const CACHE: Array<{ mask: ReachMask; ways: { [way: string]: Labels } }> = [];

function labelsFor(mask: ReachMask, way: string): Labels {
  let entry: { mask: ReachMask; ways: { [way: string]: Labels } } | null = null;
  for (let i = 0; i < CACHE.length; i++) if (CACHE[i].mask === mask) entry = CACHE[i];
  if (!entry) {
    entry = { mask: mask, ways: {} };
    CACHE.push(entry);
    if (CACHE.length > 8) CACHE.shift();
  }
  const hit = entry.ways[way];
  if (hit) return hit;
  const n = mask.nx * mask.nz;
  const ok: boolean[] = [];
  for (let m = 0; m < 4; m++) ok.push(way.charAt(m) === "1");
  const bits = passBits(way);
  const small = (bits & 1) !== 0, climbs = (bits & 2) !== 0;
  const part: number[] = new Array(n);
  for (let c = 0; c < n; c++) {
    const v = mask.data[c], m = v & 3;
    // A land cell with a barrier on it is only for a body that gets through it; a bridge's deck is land over water.
    // (The wild island's mask has no flags: this is `ok[m]` there, as before.)
    let can = ok[m];
    if (m === 0) {
      if (can && (v & BAR) !== 0 && !(small && (v & SMALL) !== 0) && !(climbs && (v & CLIMB) !== 0)) can = false;
    } else if ((v & DECK) !== 0 && ok[0]) can = true;
    part[c] = can ? -2 : -1;
  }
  let parts = 0;
  const stack: number[] = [];
  // Flood fill in cell order (row by row), so a part's number is the same on every machine.
  for (let c = 0; c < n; c++) {
    if (part[c] !== -2) continue;
    part[c] = parts;
    stack.push(c);
    while (stack.length) {
      const k = stack.pop() as number;
      const i = k % mask.nx, j = (k - i) / mask.nx;
      if (i > 0 && part[k - 1] === -2) { part[k - 1] = parts; stack.push(k - 1); }
      if (i + 1 < mask.nx && part[k + 1] === -2) { part[k + 1] = parts; stack.push(k + 1); }
      if (j > 0 && part[k - mask.nx] === -2) { part[k - mask.nx] = parts; stack.push(k - mask.nx); }
      if (j + 1 < mask.nz && part[k + mask.nx] === -2) { part[k + mask.nx] = parts; stack.push(k + mask.nx); }
    }
    parts++;
  }
  const out: Labels = { mask: mask, part: part, parts: parts };
  entry.ways[way] = out;
  return out;
}

/**
 * The way of moving one home needs: its sheet's (wayOf), widened by the home's own medium when nothing within its disc
 * `r` is ground the sheet lets it be on, yet the scene placed it there (a sheet that does not say how it moves in water:
 * a bullfrog, a water strider, a river snail on the pond bed): it moves where it lives as well.
 */
export function homeWay(mask: ReachMask, sheet: ReachSheet, x: number, z: number, r: number): string {
  return homeWayFrom(mask, wayOf(sheet), x, z, r);
}

/** `homeWay` from a way already worked out (the town's, `townWayOf`: the widening keeps its fifth character). */
export function homeWayFrom(mask: ReachMask, way: string, x: number, z: number, r: number): string {
  if (way === "air") return way;
  const ci = Math.floor((x - mask.x0) / mask.cell), cj = Math.floor((z - mask.z0) / mask.cell);
  if (ci < 0 || cj < 0 || ci >= mask.nx || cj >= mask.nz || nearestPart(mask, way, ci, cj, r) !== null) return way;
  const m = mask.data[cj * mask.nx + ci] & 3;
  return way.slice(0, m) + "1" + way.slice(m + 1);
}

/** Two ways together (a kind whose animals' homes need different ones moves as their union; "air" takes in all). */
export function unionWay(a: string, b: string): string {
  if (a === "air" || b === "air") return "air";
  let s = "";
  for (let m = 0; m < 4; m++) s += a.charAt(m) === "1" || b.charAt(m) === "1" ? "1" : "0";
  return a.length > 4 || b.length > 4 ? s + "nscb".charAt(passBits(a) | passBits(b)) : s;
}

/**
 * The part of the island an animal living at (x, z) can travel in with way `way`, as a key: two animals of a kind can
 * reach each other when their keys (under the kind's one way) are equal. "air" for a flier. A home on a cell it cannot
 * be on (a shore spot on the water's edge) takes the nearest cell it can be on within its disc `r` (ties: the lowest
 * part); none within it, or a home off the mask for a non-flier: null (it can reach nobody).
 */
export function reachPart(mask: ReachMask, way: string, x: number, z: number, r: number): string | null {
  if (way === "air") return "air";
  const ci = Math.floor((x - mask.x0) / mask.cell), cj = Math.floor((z - mask.z0) / mask.cell);
  return nearestPart(mask, way, ci, cj, r);
}

function nearestPart(mask: ReachMask, way: string, ci: number, cj: number, r: number): string | null {
  const L = labelsFor(mask, way);
  const inside = (i: number, j: number) => i >= 0 && j >= 0 && i < mask.nx && j < mask.nz;
  if (inside(ci, cj) && L.part[cj * mask.nx + ci] >= 0) return way + ":" + L.part[cj * mask.nx + ci];
  const reach = Math.max(1, Math.ceil(Math.max(r, 0) / mask.cell));
  let best = -1, bestD = Infinity;
  for (let dj = -reach; dj <= reach; dj++) {
    for (let di = -reach; di <= reach; di++) {
      const i = ci + di, j = cj + dj;
      if (!inside(i, j)) continue;
      const p = L.part[j * mask.nx + i];
      if (p < 0) continue;
      const d = di * di + dj * dj;
      if (d > reach * reach) continue;
      if (d < bestD || (d === bestD && p < best)) {
        best = p;
        bestD = d;
      }
    }
  }
  return best >= 0 ? way + ":" + best : null;
}

/** How many separate parts a way of moving has on a mask (for the doc and tests). */
export function partCount(mask: ReachMask, way: string): number {
  return way === "air" ? 1 : labelsFor(mask, way).parts;
}

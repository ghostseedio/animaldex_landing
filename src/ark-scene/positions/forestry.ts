// Ark forestry v1: logging and replanting on the wild island (owner 2026-11-17: humans "cutting down trees in the wild
// island which will destroy habitats and kill many animals in the area of the deforestation, but this should be very
// slowly and spawn in random areas of lots of trees but also to counter we have humans planting and regrowing the trees
// … the animals that it killed in the meantime won't be revived"; AnimalDex decision 379).
//
// The ONE shared forestry module: AnimalDex `supabase/functions/_shared/ark-positions/forestry.ts` (voyage-world records
// the deaths) and the landing scene's `src/ark-scene/positions/forestry.ts` (draws the felling, the stumps, the crews
// and the saplings) are byte-identical, pinned by sha like positions.ts. Both answer from the same Ark day and the same
// stands (forest-stands.json, generated by the landing's scripts/ark-forest-stands.mts from the scene's own trees), so
// every viewer sees the same trees fall at the same moment and the server kills exactly the animals whose homes the
// felling front passes.
//
// RULES FOR THIS FILE (copied verbatim into the web): positions.ts's. Pure, import-free, ES5-safe at runtime (no
// Map/Set, Math.imul/hypot, `**`, optional chaining or `??`). Changing a result changes the Ark: bump
// FORESTRY_VERSION and re-pin both copies in the same change.

export const FORESTRY_VERSION = 1;

/**
 * A logging starts every PERIOD_DAYS Ark days (22.1 real hours), jittered by up to JITTER_DAYS. The habitat-back span
 * (PLANT_FROM + PLANT_DAYS + HABITAT_GROWTH * GROW_DAYS = 23) plus the jitter is at most one period: never more than
 * one stand below habitat at once (forestry.test.ts), about 1.8% of the wild island's forest with the 15 m stands.
 */
export const PERIOD_DAYS = 24;
export const JITTER_DAYS = 1;
/** The crew's felling front crosses the stand in FELL_DAYS (55 real minutes): trees fall one at a time as it passes. */
export const FELL_DAYS = 1;
/** A felled trunk lies where it fell this long (Ark days), then is hauled away; its stump stays. */
export const HAUL_DAYS = 0.3;
/** Planters come PLANT_FROM Ark days after the logging began and plant across the stand in PLANT_DAYS. */
export const PLANT_FROM = 4;
export const PLANT_DAYS = 1;
/** A sapling grows to the tree it replaces in GROW_DAYS Ark days (33 real hours). */
export const GROW_DAYS = 36;
/** The habitat is back where the regrowth has reached this share of the tree (new animals may live there again). */
export const HABITAT_GROWTH = 0.5;
/** A stand is not logged again within this many Ark days of its last logging (fully grown and a day over). */
export const REUSE_DAYS = PLANT_FROM + PLANT_DAYS + GROW_DAYS + 1;
/** How many earlier loggings a new one keeps clear of (the reuse window, in periods, rounded up, and one more). */
export const LOOKBACK = Math.ceil(REUSE_DAYS / PERIOD_DAYS) + 1;

export interface Stand {
  id: number;
  x: number;
  z: number;
  /** The cleared disc's radius (m). */
  r: number;
  zone: string;
}

export interface StandTable {
  v: number;
  world: string;
  radius: number;
  stands: Stand[];
}

export interface Logging {
  /** The logging's number since the switch-on (0, 1, 2 …). */
  k: number;
  stand: Stand;
  /** The Ark day it begins. */
  start: number;
  /** The felling front's heading (radians, x = cos, z = sin): it crosses the disc from the far side to this one. */
  bearing: number;
}

/** A unit in [0, 1) from a key: FNV-1a, as positions.ts hashString (no Math.imul). */
export function forestUnit(key: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < key.length; i++) {
    h ^= key.charCodeAt(i);
    h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0;
  }
  return h / 4294967296;
}

/** The stands' order in cycle c (every stand once a cycle), by a hash of the cycle and the stand. */
function rawOrder(stands: Stand[], c: number): Stand[] {
  const keyed: Array<{ s: Stand; u: number }> = [];
  for (let i = 0; i < stands.length; i++) keyed.push({ s: stands[i], u: forestUnit("forestry#order#" + c + "#" + stands[i].id) });
  keyed.sort(function (a, b) { return a.u - b.u || a.s.id - b.s.id; });
  const out: Stand[] = [];
  for (let i = 0; i < keyed.length; i++) out.push(keyed[i].s);
  return out;
}

/**
 * Cycle c's order with its first LOOKBACK stands kept clear of the previous cycle's last LOOKBACK (a stand is never
 * logged twice within the reuse window across the cycles' seam). Only the head moves, and only with stands from the
 * middle, so the previous cycle's tail is its raw order: no recursion.
 */
function cycleOrder(stands: Stand[], c: number): Stand[] {
  const order = rawOrder(stands, c);
  const n = order.length;
  if (c <= 0 || n < 3 * LOOKBACK) return order;
  const prev = rawOrder(stands, c - 1);
  const tail: { [id: string]: number } = {};
  for (let i = n - LOOKBACK; i < n; i++) tail[String(prev[i].id)] = 1;
  let swap = LOOKBACK;
  for (let p = 0; p < LOOKBACK; p++) {
    if (tail[String(order[p].id)] !== 1) continue;
    while (swap < n - LOOKBACK && tail[String(order[swap].id)] === 1) swap++;
    if (swap >= n - LOOKBACK) break;
    const t = order[p];
    order[p] = order[swap];
    order[swap] = t;
    swap++;
  }
  return order;
}

/** Logging k (0, 1, 2 …) of a forestry switched on at Ark day `fromDay`, or null. */
export function loggingAt(table: StandTable | null | undefined, fromDay: number, k: number): Logging | null {
  if (!table || !table.stands || !table.stands.length || k < 0 || !(fromDay >= 0)) return null;
  const n = table.stands.length;
  const c = Math.floor(k / n);
  const stand = cycleOrder(table.stands, c)[k - c * n];
  return {
    k: k,
    stand: stand,
    start: fromDay + k * PERIOD_DAYS + JITTER_DAYS * forestUnit("forestry#start#" + k),
    bearing: 2 * Math.PI * forestUnit("forestry#bearing#" + k),
  };
}

/** Every logging whose stand is not yet fully regrown at Ark day `day` (newest last): what the scene draws. */
export function loggingsAround(table: StandTable | null | undefined, fromDay: number, day: number): Logging[] {
  const out: Logging[] = [];
  if (!table || !(day >= fromDay)) return out;
  const last = Math.floor((day - fromDay) / PERIOD_DAYS);
  for (let k = Math.max(0, last - LOOKBACK - 1); k <= last; k++) {
    const g = loggingAt(table, fromDay, k);
    if (g && g.start <= day && day < g.start + REUSE_DAYS) out.push(g);
  }
  return out;
}

/** Whether (x, z) is in the logging's stand. */
export function inStand(g: Logging, x: number, z: number): boolean {
  const dx = x - g.stand.x, dz = z - g.stand.z;
  return dx * dx + dz * dz <= g.stand.r * g.stand.r;
}

/** Where (x, z) lies along the front's way across the stand: 0 where it starts, 1 where it ends (clamped). */
export function frontShare(g: Logging, x: number, z: number): number {
  const p = -((x - g.stand.x) * Math.cos(g.bearing) + (z - g.stand.z) * Math.sin(g.bearing));
  const s = (p + g.stand.r) / (2 * g.stand.r);
  return s < 0 ? 0 : s > 1 ? 1 : s;
}

/** The Ark day the felling front reaches (x, z): a tree there falls, an animal living there loses its home. */
export function cutDay(g: Logging, x: number, z: number): number {
  return g.start + FELL_DAYS * frontShare(g, x, z);
}

/** The Ark day a sapling is planted at (x, z). */
export function plantDay(g: Logging, x: number, z: number): number {
  return g.start + PLANT_FROM + PLANT_DAYS * frontShare(g, x, z);
}

/** A replanted tree's growth at `day` (0 just planted … 1 grown), or -1 before it is planted. */
export function growthAt(g: Logging, x: number, z: number, day: number): number {
  const p = plantDay(g, x, z);
  if (day < p) return -1;
  const k = (day - p) / GROW_DAYS;
  return k > 1 ? 1 : k;
}

/** The Ark day the habitat is back over the whole stand (every sapling at HABITAT_GROWTH). */
export function habitatBackDay(g: Logging): number {
  return g.start + PLANT_FROM + PLANT_DAYS + HABITAT_GROWTH * GROW_DAYS;
}

/** Whether (x, z) is cleared habitat at `day`: the front has passed it and its sapling has not reached HABITAT_GROWTH. */
export function clearedAt(g: Logging, x: number, z: number, day: number): boolean {
  if (!inStand(g, x, z) || day < cutDay(g, x, z)) return false;
  return growthAt(g, x, z, day) < HABITAT_GROWTH;
}

export interface ForestHome {
  id: string;
  x: number;
  z: number;
  /** The Ark day it was born or arrived (an animal that came after the logging began is not killed by it). */
  since: number;
}

export interface ForestDeath {
  id: string;
  /** The Ark day it died: when the front reached its home. */
  day: number;
  k: number;
  standId: number;
}

/**
 * The deaths logging causes in (fromTick, toTick]: every animal living before its stand's logging began whose home
 * the front reaches in the window, Ark-born or carded (owner decided 2026-11-17: a carded one loses a heart, exactly
 * as at an old-age death; the server spends it and keeps the last of a kind and humans). Sorted by day then id. The
 * server records these; the scene only draws what the server recorded.
 */
export function forestDeaths(table: StandTable | null | undefined, fromDay: number, homes: ForestHome[], fromTick: number, toTick: number): ForestDeath[] {
  const out: ForestDeath[] = [];
  if (!table || !(toTick > fromTick)) return out;
  const first = Math.max(0, Math.floor((fromTick - fromDay - JITTER_DAYS - FELL_DAYS) / PERIOD_DAYS));
  const last = Math.floor((toTick - fromDay) / PERIOD_DAYS);
  for (let k = first; k <= last; k++) {
    const g = loggingAt(table, fromDay, k);
    if (!g || g.start > toTick || g.start + FELL_DAYS <= fromTick) continue;
    for (let i = 0; i < homes.length; i++) {
      const h = homes[i];
      if (h.since >= g.start || !inStand(g, h.x, h.z)) continue;
      const d = cutDay(g, h.x, h.z);
      if (d > fromTick && d <= toTick) out.push({ id: h.id, day: d, k: g.k, standId: g.stand.id });
    }
  }
  out.sort(function (a, b) { return a.day - b.day || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0); });
  return out;
}

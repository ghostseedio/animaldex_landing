// New places: the server's voyage_animal_place rule (20261111122000), for the harness and tests (the database
// assigns them in production, at insert).

export interface Placed {
  id: string;
  zone: string;
  species: string;
  slot: number;
  rank: number;
  present: boolean;
}

/**
 * {slot, rank} for a new animal in `zone`: a young one beside its first living parent in the zone (its cluster under
 * 12 living); else a herd ('group': the zone's lowest cluster of only its species, under 12) or a mate ('pair': one
 * living); else the zone's lowest slot no living animal holds. Rank: the lowest the cluster's living do not hold.
 * `living` is every living animal of the zone with a place.
 */
export function placeYoung(living: Placed[], zone: string, species: string, sociality: string | null | undefined, parents: string[] | null): { slot: number; rank: number } {
  const CLUSTER = 12;
  const inZone: Placed[] = [];
  for (let i = 0; i < living.length; i++) if (living[i].present && living[i].zone === zone) inZone.push(living[i]);
  const count = (slot: number) => {
    let n = 0;
    for (let i = 0; i < inZone.length; i++) if (inZone[i].slot === slot) n++;
    return n;
  };
  let slot = -1;
  if (parents) {
    for (let p = 0; p < parents.length && slot < 0; p++) {
      for (let i = 0; i < inZone.length; i++) {
        if (inZone[i].id === parents[p] && count(inZone[i].slot) < CLUSTER) {
          slot = inZone[i].slot;
          break;
        }
      }
    }
  }
  if (slot < 0 && (sociality === "group" || sociality === "pair")) {
    const room = sociality === "pair" ? 2 : CLUSTER;
    const slots: { [s: string]: { n: number; only: boolean } } = {};
    let best = -1;
    for (let i = 0; i < inZone.length; i++) {
      const k = String(inZone[i].slot);
      const c = slots[k] || (slots[k] = { n: 0, only: true });
      c.n++;
      if (inZone[i].species !== species) c.only = false;
    }
    for (const k in slots) {
      if (!Object.prototype.hasOwnProperty.call(slots, k)) continue;
      const s = Number(k);
      if (slots[k].only && slots[k].n < room && (best < 0 || s < best)) best = s;
    }
    slot = best;
  }
  if (slot < 0) {
    const held: { [s: string]: number } = {};
    for (let i = 0; i < inZone.length; i++) held[String(inZone[i].slot)] = 1;
    slot = 0;
    while (held[String(slot)] === 1) slot++;
  }
  const ranks: { [r: string]: number } = {};
  for (let i = 0; i < inZone.length; i++) if (inZone[i].slot === slot) ranks[String(inZone[i].rank)] = 1;
  let rank = 0;
  while (ranks[String(rank)] === 1) rank++;
  return { slot: slot, rank: rank };
}

// Time

/** One Ark day in real milliseconds: 1 Ark year (365 Ark days) = 14 real days (voyage_ark_day). */
export const ARK_DAY_MS = (86400000 * 14) / 365;
/** Ark days per real hour (about 1.086). */
export const ARK_DAYS_PER_REAL_HOUR = 365 / 14 / 24;
/** The encounter step: 15 Ark minutes (34.5 real seconds), on an absolute grid (step k is Ark day k / 96). */
export const STEPS_PER_ARK_DAY = 96;

/** The last whole step at or before `arkDay` (a value written as k / 96 reads back as k, despite float noise). */
export function stepIndex(arkDay: number): number {
  const x = arkDay * STEPS_PER_ARK_DAY;
  const r = Math.round(x);
  return Math.abs(x - r) < 1e-6 ? r : Math.floor(x);
}

/** The Ark day of step k. */
export function stepDay(k: number): number {
  return k / STEPS_PER_ARK_DAY;
}

/** Epoch milliseconds at an Ark day of a voyage started at `startedAtMs`. */
export function epochMsAt(startedAtMs: number, arkDay: number): number {
  return startedAtMs + arkDay * ARK_DAY_MS;
}

/** The island's hour (0-24), the same for everyone: UTC plus a fixed offset (the scene's ISLAND_OFFSET_HOURS, 0). */
export function islandHours(ms: number, offsetHours: number): number {
  const h = ms / 3600000 + (offsetHours || 0);
  return ((h % 24) + 24) % 24;
}

/** The sun's elevation in degrees at an island hour (the scene's sunElevationAt). */
export function sunElevation(hours: number): number {
  return 58 * Math.sin((2 * Math.PI * (hours - 6)) / 24);
}

export type Activity = "diurnal" | "nocturnal" | "crepuscular" | "any";

/** The scene's rule (lib/ark-daylight isAwake): awake with the sun at `elevation`; no activity data keeps the day's hours. */
export function isAwake(activity: string | null | undefined, elevation: number): boolean {
  if (activity === "any") return true;
  if (activity === "nocturnal") return elevation < 8;
  if (activity === "crepuscular") return elevation > -14 && elevation < 22;
  return elevation > -4;
}

/** Awake at an Ark day of a voyage (island hour from real UTC). */
export function awakeAt(activity: string | null | undefined, startedAtMs: number, arkDay: number, offsetHours?: number): boolean {
  return isAwake(activity, sunElevation(islandHours(epochMsAt(startedAtMs, arkDay), offsetHours || 0)));
}

/**
 * The awake windows of a real day, in island hours [from, to) (to may pass 24 for a window over midnight), from the
 * same thresholds as isAwake: the sun's elevation 58 sin(2 pi (h - 6) / 24) against -4 (by day), 8 (nocturnal),
 * -14..22 (crepuscular).
 */
function windowsOf(activity: string | null | undefined): number[] {
  const k = 12 / Math.PI; // radians of the sun's angle -> hours
  if (activity === "any") return [0, 24];
  if (activity === "nocturnal") {
    const b = Math.asin(8 / 58) * k;
    return [18 - b, 30 + b];
  }
  if (activity === "crepuscular") {
    const lo = Math.asin(14 / 58) * k, hi = Math.asin(22 / 58) * k;
    return [6 - lo, 6 + hi, 18 - hi, 18 + lo];
  }
  const a = Math.asin(4 / 58) * k;
  return [6 - a, 18 + a];
}

function awakePerDayHours(w: number[]): number {
  let s = 0;
  for (let i = 0; i < w.length; i += 2) s += w[i + 1] - w[i];
  return s;
}

/** Awake hours of a window list within [0, h] of one day's clock (0 <= h <= 24), windows read modulo 24. */
function awakeHoursUpTo(w: number[], h: number): number {
  let s = 0;
  for (let i = 0; i < w.length; i += 2) {
    // A window [a, b) with b possibly past 24 is [a, min(b, 24)) plus [0, b - 24).
    const a = w[i], b = w[i + 1];
    s += Math.max(0, Math.min(b, 24, h) - Math.max(a, 0));
    if (b > 24) s += Math.max(0, Math.min(b - 24, h));
    if (a < 0) s += Math.max(0, Math.min(24, h) - Math.max(24 + a, 0));
  }
  return s;
}

/** Awake hours from absolute island hour H0 to H1 (H1 >= H0). */
function awakeHoursBetween(w: number[], H0: number, H1: number): number {
  if (!(H1 > H0)) return 0;
  const per = awakePerDayHours(w);
  const d0 = Math.floor(H0 / 24), d1 = Math.floor(H1 / 24);
  const h0 = H0 - d0 * 24, h1 = H1 - d1 * 24;
  if (d0 === d1) return awakeHoursUpTo(w, h1) - awakeHoursUpTo(w, h0);
  return per - awakeHoursUpTo(w, h0) + (d1 - d0 - 1) * per + awakeHoursUpTo(w, h1);
}

/**
 * Awake Ark days between two Ark days (owner, 2026-11-11: hunger counts awake time only; the island's sun is real
 * UTC, so a diurnal predator sleeps about 13 Ark days at a stretch). -Infinity as `fromDay` gives Infinity.
 */
export function awakeArkDays(activity: string | null | undefined, startedAtMs: number, fromDay: number, toDay: number, offsetHours?: number): number {
  if (!(toDay > fromDay)) return 0;
  if (fromDay === -Infinity) return Infinity;
  const off = offsetHours || 0;
  const H0 = epochMsAt(startedAtMs, fromDay) / 3600000 + off;
  const H1 = epochMsAt(startedAtMs, toDay) / 3600000 + off;
  return awakeHoursBetween(windowsOf(activity), H0, H1) * ARK_DAYS_PER_REAL_HOUR;
}

/**
 * The first Ark day at which `need` awake Ark days have passed since `fromDay` (the inverse of awakeArkDays):
 * when a predator fed at `fromDay` is due again, or hungry. -Infinity as `fromDay` gives -Infinity.
 */
export function arkDayAfterAwake(activity: string | null | undefined, startedAtMs: number, fromDay: number, need: number, offsetHours?: number): number {
  if (fromDay === -Infinity) return -Infinity;
  if (!(need > 0)) return fromDay;
  const w = windowsOf(activity);
  const per = awakePerDayHours(w);
  const off = offsetHours || 0;
  const H0 = epochMsAt(startedAtMs, fromDay) / 3600000 + off;
  const needH = need / ARK_DAYS_PER_REAL_HOUR;
  // Whole days first, then walk the remaining day's windows.
  const d0 = Math.floor(H0 / 24);
  const h0 = H0 - d0 * 24;
  const firstLeft = per - awakeHoursUpTo(w, h0);
  let H: number;
  if (needH <= firstLeft) {
    H = d0 * 24 + hourWhenAwake(w, awakeHoursUpTo(w, h0) + needH);
  } else {
    const rest = needH - firstLeft;
    const days = Math.floor(rest / per);
    const left = rest - days * per;
    H = left > 0 ? (d0 + 1 + days) * 24 + hourWhenAwake(w, left) : (d0 + 1 + days) * 24 - 24 + lastAwakeHour(w);
  }
  return fromDay + (H - H0) / 24 * (365 / 14);
}

/** The hour of a day by which `awake` awake hours have been reached (0 < awake <= the day's total). */
function hourWhenAwake(w: number[], awake: number): number {
  let lo = 0, hi = 24;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    if (awakeHoursUpTo(w, mid) >= awake) hi = mid;
    else lo = mid;
  }
  return hi;
}

function lastAwakeHour(w: number[]): number {
  return hourWhenAwake(w, awakePerDayHours(w));
}

/** Its own lean on the clock (the scene's chronotype: up to 45 minutes either way), from its id. */
export function chronotype(id: string): number {
  return (((hashString(id + "#chrono") % 1000) / 1000) - 0.5) * 1.5;
}

// ---------------------------------------------------------------------------------------------------------------
// Hash: the scene's hashString (FNV-1a, 32 bit), with a 32-bit multiply that needs no Math.imul.

function mul32(a: number, b: number): number {
  const ah = (a >>> 16) & 0xffff, al = a & 0xffff;
  const bh = (b >>> 16) & 0xffff, bl = b & 0xffff;
  return (al * bl + (((ah * bl + al * bh) << 16) >>> 0)) | 0;
}

export function hashString(value: string): number {
  let h = 0x811c9dc5 | 0;
  for (let i = 0; i < value.length; i++) {
    h ^= value.charCodeAt(i);
    h = mul32(h, 0x01000193);
  }
  return h >>> 0;
}

/** A stable fraction in [0, 1) from a string. */
function frac(key: string): number {
  return (hashString(key) % 100000) / 100000;
}


// Hunting geometry (encounter hunting; the constants are the harness's, docs/ark/encounter-hunting.md)

export interface HuntTuning {
  /** Detection: base metres by how it moves, plus `perLength` x its length, clamped. */
  detectFly: number;
  detectSwim: number;
  detectGround: number;
  detectPerLength: number;
  detectMin: number;
  detectMax: number;
  /** Foray: `forayScale` x its home range (the scene's rangeReach is 1.5), clamped. */
  forayScale: number;
  forayMin: number;
  forayMax: number;
}

export const HUNT: HuntTuning = {
  detectFly: 8,
  detectSwim: 5,
  detectGround: 4,
  detectPerLength: 2,
  detectMin: 1.5,
  detectMax: 18,
  forayScale: 1.5,
  forayMin: 2,
  forayMax: 40,
};

function tune(t?: Partial<HuntTuning> | null): HuntTuning {
  if (!t) return HUNT;
  const out: { [k: string]: number } = {};
  for (const k in HUNT) {
    if (!Object.prototype.hasOwnProperty.call(HUNT, k)) continue;
    const v = (t as { [k: string]: number })[k];
    out[k] = typeof v === "number" && v === v ? v : (HUNT as unknown as { [k: string]: number })[k];
  }
  return out as unknown as HuntTuning;
}

/** How far a hunting predator finds prey from where it is (m): by how it moves and its size. */
export function detectionRange(sheet: Sheet, tuning?: Partial<HuntTuning> | null): number {
  const t = tune(tuning);
  const base = sheet.flies ? t.detectFly : sheet.aquatic && !sheet.amphibious ? t.detectSwim : t.detectGround;
  return Math.min(Math.max(base + t.detectPerLength * sheet.len, t.detectMin), t.detectMax);
}

/** How far from its home a hunting predator ranges (m). */
export function forayRadius(sheet: Sheet, tuning?: Partial<HuntTuning> | null): number {
  const t = tune(tuning);
  return Math.min(Math.max(t.forayScale * sheet.hr, t.forayMin), t.forayMax);
}

/** Can it be on this medium (0 land, 1 fresh, 2 shallow sea, 3 deep sea)? */
function onMedium(sheet: Sheet, medium: number): boolean {
  if (sheet.flies) return true;
  if (medium <= 0) return !sheet.aquatic || sheet.amphibious;
  if (sheet.aquatic || sheet.amphibious) return sheet.water === "" || (medium === 1 ? sheet.water !== "salt" : sheet.water !== "fresh") || sheet.amphibious;
  return medium === 2 || medium === 1 ? sheet.len >= 1.2 : false; // a big walker wades the shallows
}

/**
 * Where a due predator is at encounter step `step` while it hunts: one waypoint a step on a seeded loop about its home
 * (each its own phase and turn, from its id), the loop's radius breathing in and out so the range is swept within a
 * few dozen steps; kept to ground it can be on (the mask), pulled back towards home where it is not.
 */
export function forayAt(atlas: Atlas, home: Home, id: string, step: number, tuning?: Partial<HuntTuning> | null): { x: number; z: number } {
  const R = forayRadius(home.sheet, tuning);
  const turn = 0.45 + 0.4 * frac(id + "#foray-turn");
  const dir = frac(id + "#foray-dir") < 0.5 ? -1 : 1;
  const a = 2 * Math.PI * frac(id + "#foray-a") + dir * turn * step;
  const b = 2 * Math.PI * frac(id + "#foray-b") + 0.23 * step;
  const rho = R * (0.15 + 0.85 * (0.5 - 0.5 * Math.cos(b)));
  const dx = Math.cos(a) * rho, dz = Math.sin(a) * rho;
  // Points on the line from its home, to the centimetre (what is returned is what was tested).
  const at = (m: number) => ({ x: Math.round((home.x + dx * m) * 100) / 100, z: Math.round((home.z + dz * m) * 100) / 100 });
  const ok = (p: { x: number; z: number }) => onMedium(home.sheet, mediumAt(atlas, home.island, p.x, p.z));
  let p = at(1);
  if (!ok(p)) {
    // Back along the line to its home: the farthest point it can be on (eight halvings), else its home.
    let lo = 0, hi = 1;
    for (let i = 0; i < 8; i++) {
      const m = (lo + hi) / 2;
      if (ok(at(m))) lo = m;
      else hi = m;
    }
    p = at(lo);
  }
  return p;
}

/** Depth bands (the scene's sea-depth): at the surface anyone that hunts there takes it; the upper and middle water
 * is a swimmer's or a diving flyer's; the floor, the reef and the deep only a swimmer's. */
const SURFACE_BANDS: { [b: string]: number } = { surface: 1, pond_surface: 1 };
const DIVE_BANDS: { [b: string]: number } = { upper: 1, mid: 1, pond_mid: 1 };
const DEN_ENTRANTS: { [m: string]: number } = { slither: 1, burrow: 1, crawl: 1 };

/**
 * Can this predator take this prey where it is? Same water as it hunts in (realm by the food link, already checked;
 * here the depth band: a walker or a flyer takes only what is at or near the surface, the seabed and the reef are a
 * swimmer's), and not asleep in a den, burrow, cave, tree hole or crevice it cannot enter (snakes, burrowers and
 * crawlers can; so can a hunter no bigger than the sleeper).
 */
export function reachable(predator: Sheet, prey: Sheet, preyAsleep: boolean): boolean {
  const swimmer = predator.aquatic || predator.amphibious;
  if (prey.band) {
    if (!SURFACE_BANDS[prey.band] && !swimmer && !(predator.flies && DIVE_BANDS[prey.band])) return false;
  } else if (prey.aquatic && !prey.amphibious && !swimmer && !predator.flies) {
    return false;
  }
  // A fish takes only what is in the water (a water species, or one that swims as well as it walks).
  if (predator.aquatic && !predator.amphibious && !prey.band && !prey.aquatic && !prey.amphibious) return false;
  if (preyAsleep && prey.enclosed && !DEN_ENTRANTS[predator.move] && predator.len > prey.len) return false;
  return true;
}


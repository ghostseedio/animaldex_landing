const DEFAULT_ISLAND = "wild";
const OWN_LAPS = [0, 0, 1.25, 0, 0, 1.25, 1.25, 1.25];
const BORROWED_LAPS = [0.62, 0.62, 1.87, 0.62, 0.62, 1.87, 1.87, 1.87];
const WATER_LAPS = [0, 0, 1.25, 0, 0, 1.25, 1.25, 1.25, 0.62, 0.62, 1.87, 0.62, 0.62, 1.87, 1.87, 1.87];
const GRID = 2.5;

function gcd(a: number, b: number): number {
  while (b) {
    const t = b;
    b = a % b;
    a = t;
  }
  return a;
}

/** The scene's map/points.ts pointIndex: an index into a list of `size` and how many keys already round that point. */
export function pointIndex(key: number, size: number): { index: number; level: number } {
  const usable = Math.max(size, 1);
  let P = Math.max(1, Math.round(usable * 0.618));
  while (gcd(P, usable) !== 1) P++;
  // (key * P) % usable without losing precision for big keys: (key % usable) * P stays well under 2^53.
  return { index: ((key % usable) * P) % usable, level: Math.floor(key / usable) };
}

/** The scene's MapPoints.pick: where cluster (zone, slot) stands on a tag's list of cells. */
function pickOn(list: number[], own: boolean, zi: number, slot: number, borrowers: number, borrowerIndex: number): { x: number; z: number; level: number } {
  const n = list.length / 2;
  const key = own ? slot : slot * Math.max(borrowers, 1) + Math.max(borrowerIndex, 0);
  const lap = Math.floor(key / n);
  const p = own ? key % n : n - 1 - (key % n);
  const px = list[2 * p], pz = list[2 * p + 1];
  void zi;
  if (lap >= 4) {
    const k = lap - 4 + (own ? 0 : 1000);
    const ox = ((0.5 + k * 0.7548776662) % 1) * GRID;
    const oz = ((0.5 + k * 0.569840291) % 1) * GRID;
    return { x: px + ox - GRID / 2, z: pz + oz - GRID / 2, level: own ? lap : lap + 1 };
  }
  const laps = own ? OWN_LAPS : BORROWED_LAPS;
  return { x: px + laps[2 * lap], z: pz + laps[2 * lap + 1], level: own ? lap : lap + 1 };
}

const KIND_INDEX: { [k: string]: number } = { core: 0, cover: 1, edge: 2, plain: 3 };

/** The scene's slotKind for a map species: from its stats (the recipe's rule) and, for a rare one, its id and the slot. */
function slotKindOf(rule: unknown[], speciesId: string, zone: string, slot: number): string {
  if (rule[0] === "rare") {
    const chance = rule[1] as number;
    return rule[2] !== 1 && hashString(speciesId + "#" + zone + "#" + slot) % 100 < chance ? "cover" : "edge";
  }
  return rule[0] as string;
}

function kindOrder(kind: string): string[] {
  return kind === "cover" ? ["cover", "edge", "plain"] : kind === "plain" ? ["plain"] : [kind, "plain"];
}

/**
 * Where cluster `slot` of a species stands in its zone (its rank-0 spot), from the atlas: the scene's own pick on the
 * same lists, cells and spots (map/points.ts, map/water.ts, sea-depth.ts). Null when the atlas has no recipe for the
 * species in that zone (the hamlet's residents, a species with no model): it then takes no part in encounters.
 */
export function homeCentre(atlas: Atlas, ref: HomeRef): { x: number; z: number } | null {
  const isl = atlas.islands[ref.island || DEFAULT_ISLAND];
  if (!isl) return null;
  const row = isl.species[ref.slug];
  if (!row) return null;
  const zi = indexOfZone(atlas, ref.zone);
  let recipe: unknown[] | null = null;
  let override = -1;
  for (let i = 1; i + 2 < row.length; i += 3) {
    if (row[i] === zi) {
      recipe = isl.recipes[row[i + 1]];
      override = row[i + 2];
    }
  }
  if (!recipe) return null;
  const slot = Math.max(0, Math.floor(ref.slot || 0));
  const lists = isl.lists;
  if (override >= 0) {
    const o = isl.overrides[override];
    let lo = 0, hi = o.slots.length - 1;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      if (o.slots[mid] === slot) {
        const l = lists[o.list];
        return { x: l[2 * mid], z: l[2 * mid + 1] };
      }
      if (o.slots[mid] < slot) lo = mid + 1;
      else hi = mid - 1;
    }
  }
  const type = recipe[0];
  if (type === "F") return { x: recipe[1] as number, z: recipe[2] as number };
  if (type === "X") {
    const l = lists[recipe[1] as number], n = l.length / 2;
    const i = slot % n;
    return { x: l[2 * i], z: l[2 * i + 1] };
  }
  if (type === "C") {
    const l = lists[recipe[1] as number], n = l.length / 2;
    const i = Math.min(slot, n - 1);
    return { x: l[2 * i], z: l[2 * i + 1] };
  }
  if (type === "L") {
    // sea-depth's lakeSpot: the lake's spots shared by every zone (slot k of zone Z takes spot k * zones + Z),
    // each lap round again turned 2.4 rad about the lake's middle.
    const l = lists[recipe[1] as number], n = l.length / 2;
    const cx = recipe[2] as number, cz = recipe[3] as number;
    const idx = slot * atlas.zones.length + zi;
    const b = idx % n, lap = Math.floor(idx / n);
    const bx = l[2 * b], bz = l[2 * b + 1];
    if (!lap) return { x: bx, z: bz };
    const a = lap * 2.4, c = Math.cos(a), s = Math.sin(a);
    return { x: cx + (bx - cx) * c - (bz - cz) * s, z: cz + (bx - cx) * s + (bz - cz) * c };
  }
  if (type === "W") {
    // map/water.ts waterSpot: its own zone's slots from the list's start, a borrowed zone's from its end.
    const l = lists[recipe[1] as number], n = l.length / 2;
    const own = recipe[2] === 1;
    const lap = Math.floor(slot / n);
    const i = own ? slot % n : n - 1 - ((slot * atlas.zones.length + zi) % n);
    const li = ((own ? lap : lap + 4) % 8) * 2;
    return { x: l[2 * i] + WATER_LAPS[li], z: l[2 * i + 1] + WATER_LAPS[li + 1] };
  }
  if (type === "I") {
    // An attach point (a small animal, a perch, a limb): pointIndex on its list, its own zone's key or a borrowed key.
    const l = lists[recipe[1] as number], n = l.length / 2;
    const own = recipe[2] === 1;
    const key = own ? slot : 100000 * (zi + 1) + slot;
    const i = pointIndex(key, n).index;
    return { x: l[2 * i], z: l[2 * i + 1] };
  }
  if (type === "P") {
    // map/place.ts: its tags in order; on each, its slot kind's cells (the stats), re-picked from the next kind while
    // lapped; the first tag whose pick is free (its cell or the cell's first lap) wins, else the least lapped.
    const kind = slotKindOf(recipe[1] as unknown[], ref.speciesId, ref.zone, slot);
    const order = kindOrder(kind);
    const entries = recipe[2] as number[][];
    let chosen: { x: number; z: number; level: number } | null = null;
    let fallback: { x: number; z: number; level: number } | null = null;
    let first: { x: number; z: number; level: number } | null = null;
    for (let e = 0; e < entries.length && !chosen; e++) {
      const en = entries[e];
      const own = en[0] === 1, n = en[1], borrowers = en[2], bi = en[3];
      // entry: [own, cells, borrowers, borrower index, all, core, cover, edge, plain] (kinds only for an own list of 12+)
      const listFor = (k: string) => lists[own && n >= 12 ? en[5 + KIND_INDEX[k]] : en[4]];
      let pick = pickOn(own ? listFor(order[0]) : lists[en[4]], own, zi, slot, borrowers, bi);
      if (own) for (let o = 1; o < order.length; o++) if (pick.level > 0 && n >= 12) pick = pickOn(listFor(order[o]), own, zi, slot, borrowers, bi);
      if (!first) first = pick;
      if (pick.level <= 1) chosen = pick;
      else if (!fallback || pick.level < fallback.level) fallback = pick;
    }
    const p = chosen || fallback || first;
    return p ? { x: p.x, z: p.z } : null;
  }
  return null;
}

function indexOfZone(atlas: Atlas, zone: string): number {
  for (let i = 0; i < atlas.zones.length; i++) if (atlas.zones[i] === zone) return i;
  return 0;
}

/** A species' sheet on an island (null when the atlas does not know it). */
export function sheetOf(atlas: Atlas, slug: string, island?: string | null): Sheet | null {
  const isl = atlas.islands[island || DEFAULT_ISLAND];
  const row = isl ? isl.species[slug] : null;
  return row ? isl.sheets[row[0]] : null;
}

/**
 * The scene's groupSpread for a cluster of `size`: how far its members keep from its leader.
 */
export function groupSpread(length: number, size: number): number {
  return 2.5 + 1.6 * Math.max(length, 0.3) * Math.sqrt(Math.max(size, 1));
}

/** The disc an animal is found in around its home: its cluster's spread (rank > 0) plus its everyday range. */
export function preyDiscRadius(sheet: Sheet, rank: number): number {
  const spread = rank > 0 ? groupSpread(sheet.len, rank + 1) : 0;
  return Math.max(0.3, spread + sheet.hr);
}

/** An animal's home: its cluster's spot and its disc, or its stored home (player control) where it has one. */
export function homeOf(atlas: Atlas, ref: HomeRef, override?: HomeOverride | null): Home | null {
  const island = (override && override.island) || ref.island || DEFAULT_ISLAND;
  const sheet = sheetOf(atlas, ref.slug, island);
  if (!sheet) return null;
  let x: number, z: number;
  if (override && typeof override.x === "number" && typeof override.z === "number") {
    x = override.x;
    z = override.z;
  } else {
    const c = homeCentre(atlas, { island: island, zone: ref.zone, slug: ref.slug, speciesId: ref.speciesId, slot: ref.slot, rank: ref.rank });
    if (!c) return null;
    x = c.x;
    z = c.z;
  }
  const r = override && typeof override.r === "number" ? override.r : preyDiscRadius(sheet, ref.rank || 0);
  return { island: island, zone: ref.zone, slug: ref.slug, x: x, z: z, r: r, sheet: sheet };
}

/** Medium at a point: 0 land, 1 fresh water, 2 shallow sea (under 1.5 m), 3 deep sea; -1 off the mask. */
export function mediumAt(atlas: Atlas, island: string | null | undefined, x: number, z: number): number {
  const isl = atlas.islands[island || DEFAULT_ISLAND];
  if (!isl) return -1;
  const m = isl.mask;
  const i = Math.floor((x - m.x0) / m.cell), j = Math.floor((z - m.z0) / m.cell);
  if (i < 0 || j < 0 || i >= m.nx || j >= m.nz) return 3;
  return m.data[j * m.nx + i] & 3;
}


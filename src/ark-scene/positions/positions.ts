// The prey grid: discs in square cells, rebuilt only when who is aboard changes (an arrival, a birth, a death)

export interface Grid<T extends { id: string }> {
  cell: number;
  cells: { [key: string]: Array<{ x: number; z: number; r: number; item: T }> };
}

export function newGrid<T extends { id: string }>(cell: number): Grid<T> {
  return { cell: cell > 0 ? cell : 8, cells: {} };
}

function cellKey(island: string, i: number, j: number): string {
  return island + "|" + i + "|" + j;
}

/** Adds a disc to every cell it touches. */
export function gridAdd<T extends { id: string }>(g: Grid<T>, island: string, x: number, z: number, r: number, item: T): void {
  const i0 = Math.floor((x - r) / g.cell), i1 = Math.floor((x + r) / g.cell);
  const j0 = Math.floor((z - r) / g.cell), j1 = Math.floor((z + r) / g.cell);
  const d = { x: x, z: z, r: r, item: item };
  for (let i = i0; i <= i1; i++) {
    for (let j = j0; j <= j1; j++) {
      const k = cellKey(island, i, j);
      const list = g.cells[k];
      if (list) list.push(d);
      else g.cells[k] = [d];
    }
  }
}

/**
 * Every disc within `range` of a point (distance to the disc's middle <= range + its radius), each once (by item
 * id), cell by cell and in the order added (deterministic), with the distance to its middle.
 */
export function gridQuery<T extends { id: string }>(g: Grid<T>, island: string, x: number, z: number, range: number): Array<{ item: T; d: number; x: number; z: number; r: number }> {
  const out: Array<{ item: T; d: number; x: number; z: number; r: number }> = [];
  const seen: { [k: string]: number } = {};
  const i0 = Math.floor((x - range) / g.cell), i1 = Math.floor((x + range) / g.cell);
  const j0 = Math.floor((z - range) / g.cell), j1 = Math.floor((z + range) / g.cell);
  for (let i = i0; i <= i1; i++) {
    for (let j = j0; j <= j1; j++) {
      const list = g.cells[cellKey(island, i, j)];
      if (!list) continue;
      for (let k = 0; k < list.length; k++) {
        const e = list[k];
        const dx = e.x - x, dz = e.z - z;
        const d = Math.sqrt(dx * dx + dz * dz);
        if (d > range + e.r) continue;
        if (seen[e.item.id] === 1) continue;
        seen[e.item.id] = 1;
        out.push({ item: e.item, d: d, x: e.x, z: e.z, r: e.r });
      }
    }
  }
  return out;
}


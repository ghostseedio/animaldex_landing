export interface AtlasIsland {
  mask: { x0: number; z0: number; cell: number; nx: number; nz: number; data: number[] };
  lists: number[][];
  recipes: unknown[][];
  /** slug -> [sheet, then per zone: zone index, recipe, override (-1: none)]. */
  species: { [slug: string]: number[] };
  sheets: Sheet[];
  /**
   * Slots where the scene's spot is not the recipe's (its ground there would not take the animal, so the scene went on
   * to its next tag; a rare kind's cover): ascending slots and, at the same positions, the scene's own spots.
   */
  overrides: Array<{ slots: number[]; list: number }>;
}

export interface Atlas {
  v: number;
  zones: string[];
  islands: { [island: string]: AtlasIsland };
}

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

function b64bytes(s: string): number[] {
  const out: number[] = [];
  let buf = 0, bits = 0;
  for (let i = 0; i < s.length; i++) {
    const c = B64.indexOf(s.charAt(i));
    if (c < 0) continue; // padding, line breaks
    buf = (buf << 6) | c;
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out.push((buf >> bits) & 0xff);
    }
  }
  return out;
}

/** int16 little-endian pairs (decimetres) -> [x0, z0, x1, z1, ...] in metres. */
function b64points(s: string): number[] {
  const b = b64bytes(s);
  const out: number[] = [];
  for (let i = 0; i + 1 < b.length; i += 2) {
    let v = b[i] | (b[i + 1] << 8);
    if (v >= 32768) v -= 65536;
    out.push(v / 10);
  }
  return out;
}

/** The atlas as stored (JSON, lists and mask base64) -> ready to use. Decode once and keep it. */
export function decodeAtlas(raw: unknown): Atlas {
  const j = raw as { v: number; zones: string[]; islands: { [k: string]: { mask: { x0: number; z0: number; cell: number; nx: number; nz: number; data: string }; lists: string[]; recipes: unknown[][]; species: { [s: string]: number[] }; sheets: unknown[][]; overrides?: Array<[number[], number]> } } };
  if (!j || j.v !== 1) throw new Error("ark-positions: atlas version " + (j ? j.v : "missing") + " is not 1");
  const islands: { [k: string]: AtlasIsland } = {};
  for (const name in j.islands) {
    if (!Object.prototype.hasOwnProperty.call(j.islands, name)) continue;
    const i = j.islands[name];
    const sheets: Sheet[] = [];
    for (let s = 0; s < i.sheets.length; s++) {
      const r = i.sheets[s] as [string, number, number, string, number, string, string, string, number];
      const flags = r[8] || 0;
      sheets.push({ move: r[0], len: r[1], hr: r[2], roost: r[3], enclosed: r[4] === 1, band: r[5], water: r[6], activity: r[7], flies: (flags & 1) !== 0, aquatic: (flags & 2) !== 0, amphibious: (flags & 4) !== 0 });
    }
    const lists: number[][] = [];
    for (let l = 0; l < i.lists.length; l++) lists.push(b64points(i.lists[l]));
    const overrides: Array<{ slots: number[]; list: number }> = [];
    const ov = i.overrides || [];
    for (let o = 0; o < ov.length; o++) overrides.push({ slots: ov[o][0], list: ov[o][1] });
    islands[name] = {
      mask: { x0: i.mask.x0, z0: i.mask.z0, cell: i.mask.cell, nx: i.mask.nx, nz: i.mask.nz, data: b64bytes(i.mask.data) },
      lists: lists,
      recipes: i.recipes,
      species: i.species,
      sheets: sheets,
      overrides: overrides,
    };
  }
  return { v: 1, zones: j.zones, islands: islands };
}


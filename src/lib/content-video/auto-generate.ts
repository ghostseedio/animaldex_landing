// Unattended page videos, run by the VM timer (POST /api/cron/video-auto-generate):
// each run makes one video from a page family the hook lab ranks highest (its
// videos have scored best; some picks stay random), re-weighted by the format
// lab's verdicts (a scaling format 3×, one in its first 10 videos 1.5×, a
// retired one rarely), and a random page of it
// that has no video yet, exactly as "Generate video" in /admin/story-videos,
// except that its script must pass the test audience (social-lab/review.ts)
// within three drafts or no clips are made. At most two a day: quality over volume.
// A video takes 5-20 minutes, so a run waits while one is being made (or a
// social upload is encoding) instead of queuing. A finished auto video is
// published to its page, which also makes it eligible for the auto-share.

function numberEnv(name: string, fallback: number) {
    const value = Number(process.env[name]);
    return Number.isFinite(value) && value > 0 ? value : fallback;
}

/** Puts a finished auto video on its page; the page picks it up within its revalidate window. */
async function publishIfReady(id: string) {
    const row = await getContentVideo(id);
    if (!row || row.status !== "ready" || row.published_at || row.archived_at) return false;
    await updateContentVideo(id, {published_at: new Date().toISOString()});
    void submitIndexNow([videoWatchPath(row.source_type, row.source_slug), "/videos"]);
    console.info(`[video-auto-generate] published ${row.source_type}/${row.source_slug}`);
    return true;
}

export type AutoGenerateResult = {ok: true; acted: boolean; summary: string; ref?: string; detail?: Record<string, unknown>};

/** Articles this new jump the queue for a video. */
const FRESH_ARTICLE_MS = 72 * 3_600_000;

/** Published page videos from the last two days that no platform has had yet (a failed attempt does not count). */
async function unpostedRecentVideos() {
    const since = Date.now() - 48 * 3_600_000;
    const [videos, posts] = await Promise.all([listContentVideos(200), listPosts(1000)]);
    const shared = new Set(posts.filter((post) => post.status !== "failed").map((post) => post.media_path));
    return videos.filter((video) => video.status === "ready" && video.published_at && !video.archived_at && video.video_path
        && Date.parse(video.published_at) >= since && !shared.has(video.video_path)).length;
}

async function run(): Promise<AutoGenerateResult> {
    if (process.env.CONTENT_VIDEO_AUTO_DISABLED?.trim() === "1") return {ok: true, acted: false, summary: "CONTENT_VIDEO_AUTO_DISABLED=1"};
    if (contentVideoBusy()) return {ok: true, acted: false, summary: "A video is still being made"};
    if (await isSocialUploadRunning()) return {ok: true, acted: false, summary: "A social upload is still running"};

    // Loose ends from earlier runs: publish what finished while no request was
    // around, and resume a video a restart interrupted (its paid clips are kept).
    const [autoIds, allRows] = await Promise.all([autoGeneratedVideoIds(), listContentVideos(200)]);
    const rows = allRows.filter((row) => autoIds.has(row.id));
    const published: string[] = [];
    for (const row of rows) if (await publishIfReady(row.id)) published.push(row.source_title);
    const interrupted = rows.find((row) => row.status !== "ready" && row.status !== "failed");
    if (interrupted) {
        await updateContentVideo(interrupted.id, {status: resumeStatus(interrupted), error: null, progress: "Resuming"});
        startContentVideoJob(interrupted.id, async () => {
            await publishIfReady(interrupted.id);
        }, {reviewGate: true});
        return {ok: true, acted: true, summary: `Resumed the interrupted video for “${interrupted.source_title}”`, ref: interrupted.id, detail: {resumed: true, published}};
    }

    // Fewer, better videos: at most CONTENT_VIDEO_DAILY_MAX a day (Jakarta day,
    // as the share caps count it). A script held back by the test audience made
    // no clips and does not count.
    const dailyMax = numberEnv("CONTENT_VIDEO_DAILY_MAX", 2);
    const madeToday = rows.filter((row) => row.status !== "failed" && Date.parse(row.created_at) >= dayStartMs(Date.now())).length;
    if (madeToday >= dailyMax) {
        return {ok: true, acted: false, summary: `${madeToday} videos made today (CONTENT_VIDEO_DAILY_MAX ${dailyMax}); waiting for tomorrow`, detail: {published}};
    }

    // Make videos only as fast as the daily caps post them: a pile of unposted
    // videos is money spent on nothing. Older ones age out of the count.
    const backlogMax = numberEnv("CONTENT_VIDEO_BACKLOG_MAX", 4);
    const backlog = await unpostedRecentVideos();
    if (backlog >= backlogMax) {
        return {ok: true, acted: false, summary: `${backlog} recent videos are still waiting for their first post (CONTENT_VIDEO_BACKLOG_MAX ${backlogMax}); waiting`, detail: {published}};
    }

    const maxVideoUSD = numberEnv("CONTENT_VIDEO_MAX_USD", 1.5);
    const dailyBudgetUSD = numberEnv("CONTENT_VIDEO_DAILY_BUDGET_USD", 10);
    const spent = await spentTodayUSD();
    if (!budgetAllowsVideo(spent, maxVideoUSD, dailyBudgetUSD)) {
        return {ok: true, acted: false, summary: `Today's clip spend is $${spent.toFixed(2)} of the $${dailyBudgetUSD} budget; waiting for tomorrow (UTC)`, detail: {published}};
    }

    const available: Partial<Record<SourceType, VideoCandidate[]>> = Object.fromEntries(await Promise.all(SOURCE_TYPES.map(async (type) => {
        const [candidates, used] = await Promise.all([listPageCandidates(type), usedSourceSlugs(type)]);
        return [type, candidates.filter((candidate) => !used.has(candidate.slug))] as const;
    })));
    // Higgsfield out of credit (the latest video's clips failed for it): only
    // scan reveals, which are made of our own footage, until a clip comes back.
    const creditFailure = higgsfieldCreditFailure(allRows, new Date());
    if (creditFailure) {
        for (const type of Object.keys(available) as SourceType[]) if (type !== "scan") delete available[type];
    }
    // Fast lane: an article published in the last 72 hours (news is worth most while
    // it is news) gets its video before any random page; newest first.
    const fresh = (available.blog ?? [])
        .filter((candidate) => Date.now() - Date.parse(candidate.publishedAt) < FRESH_ARTICLE_MS)
        .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
    // The hook lab's order of page families, re-weighted by what the format lab says about the format each makes.
    const [labOrder, verdicts] = await Promise.all([rankSourceTypes("video", SOURCE_TYPES), formatVerdicts()]);
    const order = weightSourceOrder(labOrder, verdicts);
    const unavailable: SourceType[] = [];
    // A page can lack the images a video needs; try the fresh ones, then a few random picks, before giving up.
    for (let attempt = 0; attempt < 5 + fresh.length; attempt += 1) {
        const freshPick = fresh.shift();
        const pick = freshPick ? {type: "blog" as const, page: freshPick} : pickRandomSource(available, Math.random, order);
        if (!pick) return {ok: true, acted: false, summary: creditFailure ? `Higgsfield is out of credit (${creditFailure.slice(0, 120)}) and no scan reveal is left; top up at cloud.higgsfield.ai` : "Every page already has a video", detail: {published}};
        const {type, page} = pick;
        available[type] = available[type]!.filter((candidate) => candidate.slug !== page.slug);
        const source = await loadPageSource(type, page.slug);
        if (!source || source.images.length < minimumImages(type)) continue;
        let inserted: Awaited<ReturnType<typeof insertContentVideo>>;
        try {
            inserted = await insertContentVideo(type, page.slug, source.title);
        } catch (error) {
            // A family the database does not accept yet (its migration is not applied): skip it, try another.
            if (/source_type_known|23514/.test(error instanceof Error ? error.message : String(error))) {
                delete available[type];
                unavailable.push(type);
                continue;
            }
            throw error;
        }
        const row = inserted;
        if (!row) continue;
        if (!startContentVideoJob(row.id, async () => {
            await publishIfReady(row.id);
        }, {reviewGate: true})) {
            return {ok: true, acted: false, summary: "A video started elsewhere at the same moment", detail: {published}};
        }
        return {ok: true, acted: true, summary: `Making a ${type} video from “${source.title}”${creditFailure ? " (Higgsfield is out of credit: footage only)" : ""}`, ref: row.id, detail: {type, slug: page.slug, fresh: Boolean(freshPick), order, published, ...(unavailable.length ? {unavailable} : {})}};
    }
    return {ok: true, acted: false, summary: `No usable page in five random picks; trying again next run${unavailable.length ? ` (not accepted by the database yet: ${unavailable.join(", ")}; apply migration 20261106124500)` : ""}`, detail: {published, unavailable}};
}

/** One timer run, logged to admin_automation_runs. */
export async function runAutoGenerate(): Promise<AutoGenerateResult> {
    try {
        const result = await run();
        await recordAutomationRun({job: "video-auto-generate", outcome: result.acted ? "acted" : "skipped", summary: result.summary, ref: result.ref, detail: result.detail});
        return result;
    } catch (error) {
        const summary = error instanceof Error ? error.message : String(error);
        await recordAutomationRun({job: "video-auto-generate", outcome: "failed", summary});
        throw error;
    }
}

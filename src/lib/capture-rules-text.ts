const RIGHT_TO_LEFT = new Set(["ar", "fa", "he", "ur"]);
const LANGUAGE_ALIASES: Record<string, string> = {no: "nb", nn: "nb", iw: "he", in: "id", tl: "fil"};

/** The first of the browser's languages the rules are translated into, else English. */
export function captureRulesLanguage(preferred: readonly string[]): string {
    for (const raw of preferred) {
        const tag = raw.toLowerCase();
        const [base, region] = tag.split("-");
        if (base === "zh") {
            const traditional = tag.includes("hant") || region === "tw" || region === "hk" || region === "mo";
            return traditional ? "zh-Hant" : "zh-Hans";
        }
        const code = LANGUAGE_ALIASES[base] ?? base;
        if (CAPTURE_RULES_TEXT[code]) return code;
    }
    return "en";
}

export function isRightToLeftLanguage(language: string): boolean {
    return RIGHT_TO_LEFT.has(language);
}

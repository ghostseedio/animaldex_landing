import {getSupabaseHeaders, getSupabaseServiceKey, getSupabaseUrl} from "@/lib/supabase-http";

// The run log of the VM-timer automations (social auto-share, page-video
// auto-generate): supabase/migrations/20261020120000_admin_automation_runs.sql.

export const AUTOMATION_JOBS = ["social-auto-share", "video-auto-generate"] as const;
export type AutomationJob = (typeof AUTOMATION_JOBS)[number];
export type AutomationOutcome = "acted" | "skipped" | "failed";

export type AutomationRun = {
    id: string;
    job: AutomationJob;
    outcome: AutomationOutcome;
    summary: string;
    ref: string | null;
    detail: Record<string, unknown> | null;
    created_at: string;
};

function rest(path: string, init: RequestInit & {prefer?: string} = {}) {
    const url = getSupabaseUrl();
    const key = getSupabaseServiceKey();
    if (!url || !key) throw new Error("Supabase service role is not configured");
    const headers: Record<string, string> = getSupabaseHeaders(key, {"Content-Type": "application/json"});
    if (init.prefer) headers.Prefer = init.prefer;
    return fetch(`${url}/rest/v1/${path}`, {...init, headers, cache: "no-store"});
}

/** Logs one run. Never throws: a missing log row must not fail the automation itself. */
export async function recordAutomationRun(run: Pick<AutomationRun, "job" | "outcome" | "summary"> & Partial<Pick<AutomationRun, "ref" | "detail">>) {
    try {
        const response = await rest("admin_automation_runs", {
            method: "POST",
            prefer: "return=minimal",
            body: JSON.stringify({job: run.job, outcome: run.outcome, summary: run.summary.slice(0, 2000), ref: run.ref ?? null, detail: run.detail ?? null})
        });
        if (!response.ok) console.error(`[automation-runs] logging ${run.job} failed (${response.status}): ${(await response.text()).slice(0, 300)}`);
    } catch (error) {
        console.error(`[automation-runs] logging ${run.job} failed`, error);
    }
}

export async function listAutomationRuns(job: AutomationJob, limit = 20): Promise<AutomationRun[]> {
    const response = await rest(`admin_automation_runs?job=eq.${job}&select=*&order=created_at.desc&limit=${limit}`);
    if (!response.ok) throw new Error(`Loading automation runs failed (${response.status}): ${(await response.text()).slice(0, 300)}`);
    return await response.json() as AutomationRun[];
}

/** Content-video ids the auto-generate timer started (its "acted" runs). */
export async function autoGeneratedVideoIds(limit = 100) {
    const response = await rest(`admin_automation_runs?job=eq.video-auto-generate&outcome=eq.acted&ref=not.is.null&select=ref&order=created_at.desc&limit=${limit}`);
    if (!response.ok) throw new Error(`Loading auto-generated videos failed (${response.status})`);
    return new Set((await response.json() as Array<{ref: string}>).map((row) => row.ref));
}

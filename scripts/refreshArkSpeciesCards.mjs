#!/usr/bin/env node
/**
 * The Ark card's species facts (lane ARK-SIMPLE, owner 2026-11-20: "add the animal's lesson / power and pull their index
 * numbers too"), compacted from the published build-time snapshots so /api/ark/species-card needs no database for most
 * species: each species page's AnimalDex index number (`databaseSource.animalDexNumber`, the catalog's `animaldex_number`)
 * and its Animal Power's name and one-line lesson (`published-species-powers.json`, else the lesson pages' catalog
 * rows: `principle_name`, `core_lesson`). Run after `npm run refresh:published-seo`:
 *   node scripts/refreshArkSpeciesCards.mjs
 * Writes src/data/ark-species-cards.json: {bySlug: {slug: [number|null, power|null, lesson|null]}, byId: {species_profile_id: slug}}.
 */
import {readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => JSON.parse(readFileSync(path.join(root, "src/data", file), "utf8"));
const pages = read("published-seo-animal-pages.json").entries;
const profiles = read("published-seo-static-species-profiles.json").entries;
const overlay = read("published-seo-static-species-overlay.json").entries;
const powers = read("published-species-powers.json").powers;
const lessons = new Map(read("published-seo-lesson-pages.json").entries.map((row) => [row.slug, row]));

const clean = (value) => (typeof value === "string" && value.trim() ? value.trim() : null);
const bySlug = {};
const byId = {};
const number = new Map();
for (const entry of pages) {
    const n = entry.databaseSource?.animalDexNumber;
    if (Number.isInteger(n) && n > 0) number.set(entry.slug, n);
    if (entry.speciesProfileId) byId[entry.speciesProfileId.toLowerCase()] = entry.slug;
}
for (const [slug, entry] of Object.entries(overlay)) {
    const n = entry.animalDexNumber;
    if (Number.isInteger(n) && n > 0 && !number.has(slug)) number.set(slug, n);
}
for (const [slug, entry] of Object.entries(profiles)) {
    if (entry.speciesProfileId && !byId[entry.speciesProfileId.toLowerCase()]) byId[entry.speciesProfileId.toLowerCase()] = slug;
}
const slugs = new Set([...number.keys(), ...Object.keys(powers), ...lessons.keys()]);
for (const slug of [...slugs].sort()) {
    const power = powers[slug];
    const lesson = lessons.get(slug);
    const name = clean(power?.name) ?? clean(lesson?.principleName);
    const line = clean(power?.lesson) ?? clean(lesson?.coreLesson) ?? clean(power?.expression) ?? clean(lesson?.principleExpression);
    const n = number.get(slug) ?? null;
    if (n === null && !name) continue;
    bySlug[slug] = [n, name, name ? line : null];
}
const out = {note: "Generated by scripts/refreshArkSpeciesCards.mjs from the published species snapshots. Read by src/data/ark-species-card.ts.", bySlug, byId};
writeFileSync(path.join(root, "src/data/ark-species-cards.json"), JSON.stringify(out) + "\n");
console.log(`${Object.keys(bySlug).length} species, ${Object.keys(byId).length} ids`);

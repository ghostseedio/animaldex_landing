/**
 * ARK-CANOPY: where an ape's hand can hold. For every asset tree's limb, hang and branch point (`tree-attach.json`,
 * in each tag's own order), the nearest point on the tree's drawn WOOD (lod0's triangles that do not flutter: the
 * same split `ark-tree-attach.mjs` makes) and how far it is. `canopy-scene.ts` moves a brachiator's hold onto that
 * wood and drops a hold with no wood within 10 cm (a leaf clump, a frond's tip), so a hand is never shown on air.
 * The distance is the WORST over lod0, lod1 and lod2: a twig drawn only at full detail is gone a few metres off (a
 * hand there would hold air in a shot from 4 m), so only wood every near level draws counts.
 * Writes `src/ark-scene/canopy-wood.json`: {assets: {id: {tag: [[distance, x, y, z], ...]}}} in the asset's own
 * metres (rounded to the millimetre), the point on lod0's wood. Run after `ark-tree-attach.mjs` whenever the trees change.
 */
import {readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const nm = path.join(root, "node_modules");
const THREE = await import(pathToFileURL(path.join(nm, "three/build/three.module.js")).href);
const {GLTFLoader} = await import(pathToFileURL(path.join(nm, "three/examples/jsm/loaders/GLTFLoader.js")).href);
const {MeshoptDecoder} = await import(pathToFileURL(path.join(nm, "three/examples/jsm/libs/meshopt_decoder.module.js")).href);
const {Vector3, Triangle} = THREE;

const manifest = JSON.parse(readFileSync(path.join(root, "src/ark-scene/assets-manifest.json"), "utf8"));
const base = path.join(root, "public", manifest.base);
const attach = JSON.parse(readFileSync(path.join(root, "src/ark-scene/tree-attach.json"), "utf8")).assets;
const TAGS = ["limb", "canopy_hang", "branch"];
const loader = new GLTFLoader();
loader.setMeshoptDecoder(MeshoptDecoder);

async function wood(id, level) {
    const lod = manifest.assets[id]?.lods.find((l) => l.level === level);
    if (!lod) return null;
    const buf = readFileSync(path.join(base, lod.file));
    const gltf = await new Promise((resolve, reject) => loader.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), "", resolve, reject));
    let geometry = null;
    gltf.scene.traverse((o) => {
        if (!geometry && o.isMesh) geometry = o.geometry;
    });
    const P = geometry.getAttribute("position");
    const W = geometry.getAttribute("color_1");
    const index = geometry.index;
    const out = [];
    for (let t = 0; t < index.count / 3; t++) {
        const ids = [index.getX(3 * t), index.getX(3 * t + 1), index.getX(3 * t + 2)];
        // (Leaves flutter, COLOR_1 z or w set; wood has neither.)
        if (ids.some((i) => W.getZ(i) > 0.002 || W.getW(i) > 0.002)) continue;
        out.push(new Triangle(...ids.map((i) => new Vector3(P.getX(i), P.getY(i), P.getZ(i)))));
    }
    return out;
}

const r3 = (v) => Math.round(v * 1000) / 1000;
const assets = {};
for (const id of Object.keys(attach).sort()) {
    const levels = [];
    for (const level of ["lod0", "lod1", "lod2"]) {
        const tris = await wood(id, level);
        if (tris) levels.push(tris);
    }
    if (!levels.length) continue;
    const own = {};
    const q = new Vector3();
    const nearest = (tris, p, at) => {
        let best = Infinity;
        for (const t of tris) {
            t.closestPointToPoint(p, q);
            const d = q.distanceToSquared(p);
            if (d < best) {
                best = d;
                at?.copy(q);
            }
        }
        return Math.sqrt(best);
    };
    for (const tag of TAGS) {
        own[tag] = attach[id].filter((row) => row[0] === tag).map((row) => {
            const p = new Vector3(row[1], row[2], row[3]);
            const at = new Vector3();
            let worst = nearest(levels[0], p, at);
            for (const tris of levels.slice(1)) worst = Math.max(worst, nearest(tris, at));
            return [r3(worst), r3(at.x), r3(at.y), r3(at.z)];
        });
    }
    assets[id] = own;
    const near = (tag) => own[tag].filter((r) => r[0] <= 0.1).length + "/" + own[tag].length;
    console.log(id, TAGS.map((t) => `${t} ${near(t)}`).join("  "));
}
writeFileSync(path.join(root, "src/ark-scene/canopy-wood.json"), JSON.stringify({about: "Generated by scripts/ark-canopy-wood.mjs: per asset tree and tag (limb, canopy_hang, branch, in tree-attach.json's order), [distance to the nearest drawn lod0 wood (m), that wood point x, y, z] in the asset's own metres. Do not edit by hand.", assets}) + "\n");
